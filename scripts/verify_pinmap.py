"""Check the MCU pin assignments in design.py against ST's STM32CubeMX MCU database.

Source of truth: STM32CubeMX 6.18.1 db/mcu/<part>.xml (package pin list + signals per pin).
Writes validation/logs/pinmap_check.md. Exit code 1 if any assignment is not supported.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(__file__))
import design  # noqa: E402

CUBEMX_DB = os.path.expanduser(r"~/AppData/Local/Programs/STM32CubeMX/db/mcu")
NS = "{http://mcd.rou.st.com/modules.php?name=mcu}"

# Intended function per (ref, pin) - the claim being verified.
INTENT = {
    "U501": {
        "13": "SPI3_SCK", "15": "SPI3_MOSI", "9": "SPI3_NSS", "20": "TIM2_CH1", "5": "TIM2_CH2", "48": "GPIO",
        "32": "USART2_TX", "29": "USART2_RX", "31": "USART2_DE", "21": "LPUART1_TX", "12": "LPUART1_RX",
        "4": "USART1_TX", "7": "I2C3_SCL", "6": "I2C3_SDA", "19": "GPIO", "33": "GPIO", "23": "GPIO",
        "28": "GPIO", "10": "GPIO", "14": "ADC4_IN10", "30": "GPIO", "27": "DEBUG_JTMS-SWDIO",
        "26": "DEBUG_JTCK-SWCLK", "24": "DEBUG_JTDO-SWO", "17": "RCC_OSC32_IN", "16": "RCC_OSC32_OUT",
        "34": "GPIO", "36": "<Reset>", "37": "<MonoIO>",
    },
    "U601": {
        "19": "GPIO", "20": "GPIO", "17": "TIM3_CH1", "18": "TIM3_CH2", "13": "USART2_TX", "14": "USART2_RX",
        "29": "USART1_TX", "32": "USART1_RX", "21": "GPIO", "35": "DEBUG_SWDIO", "36": "DEBUG_SWCLK",
        "10": "<NRST>",
    },
}
PARTS = {"U501": "STM32WBA55CGUx.xml", "U601": "STM32C031C(4-6)Tx.xml"}


def load(xmlname):
    root = ET.parse(os.path.join(CUBEMX_DB, xmlname)).getroot()
    pins = {}
    for p in root.iter(NS + "Pin"):
        pins.setdefault(p.get("Position"), []).append(
            (p.get("Name"), p.get("Type"), [s.get("Name") for s in p.iter(NS + "Signal")]))
    return root.get("RefName"), pins


def main():
    root, sheets = design.build()
    parts = {p.ref: p for s in sheets for p in s.parts}
    out = ["# MCU pin-map check against STM32CubeMX database", "",
           f"Database: `{CUBEMX_DB}` (STM32CubeMX 6.18.1). Generated by `scripts/verify_pinmap.py`.", "",
           "This checks that each assigned function exists on that package pin in ST's data, and that",
           "no signal is used twice. It does not check clock trees, peripheral conflicts at run time,",
           "5 V tolerance, or electrical ratings (ST datasheet still required).", ""]
    bad = 0
    for ref, xmlname in PARTS.items():
        refname, pins = load(xmlname)
        part = parts[ref]
        out += [f"## {ref} {refname}", "", "| Pin | CubeMX name | Type | Net | Intended | Result |",
                "| --- | --- | --- | --- | --- | --- |"]
        used = {}
        for num in sorted(set(part.nets) | set(part.nc), key=lambda n: int(n)):
            entries = pins.get(num)
            if not entries:
                out.append(f"| {num} | (not in DB) | | | | **FAIL** |")
                bad += 1
                continue
            names = "/".join(e[0] for e in entries)
            typ = entries[0][1]
            sigs = [s for e in entries for s in e[2]]
            net = part.nets.get(num, "NC")
            want = INTENT[ref].get(num)
            if typ == "Power":
                res = "power pin"
            elif want is None:
                res = "no function claimed" if num in part.nc else "unchecked"
            elif want == "<Reset>":
                res = "OK" if typ == "Reset" else "**FAIL**"
            elif want == "<MonoIO>":
                res = "OK" if typ == "MonoIO" else "**FAIL**"
            elif want == "<NRST>":
                res = "OK" if any("NRST" in e[0] for e in entries) else "**FAIL**"
            elif want == "GPIO":
                res = "OK" if "GPIO" in sigs else "**FAIL**"
            else:
                res = "OK" if want in sigs else "**FAIL**"
                if want in used:
                    res = f"**FAIL** (also on pin {used[want]})"
                used[want] = num
            if "FAIL" in res:
                bad += 1
            out.append(f"| {num} | {names} | {typ} | `{net}` | {want or ''} | {res} |")
        out.append("")
    out.append(f"**Result: {bad} failing assignment(s).**")
    path = os.path.join(os.path.dirname(__file__), "..", "validation", "logs", "pinmap_check.md")
    with open(path, "w", encoding="utf8") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(l for l in out if "FAIL" in l or l.startswith(("##", "**Result"))))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())

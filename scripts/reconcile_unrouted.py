"""Net-level reconciliation of the DRC unconnected pairs (read-only).

Run with KiCad's Python:
  python.exe -I scripts/reconcile_unrouted.py CUR_DRC_JSON BASE_DRC_JSON MOVE_LOG BOM_DETAILED_CSV PCB > OUT.md

Each unconnected pair goes into exactly one group, tested in this order:
  W  WBA55-related: nets waiting for the ST documents (supply / clock / RF)
  P  placeholder or intentionally unfitted: an endpoint pad belongs to a DNP part or a PLACEHOLDER part
  R  opened by the approved placement rip-up (net listed as ripped in the move log)
  G  genuine missing connection that existed before the placement change
For every net the full pad list (with part status) is printed so both ends can be checked by hand.
"""
import csv
import json
import math
import re
import sys
from collections import defaultdict

import pcbnew

WBA = {"HSE_IN", "HSE_OUT", "LSE_IN", "RF_MCU", "WBA_VDD11", "WBA_VDDANA", "WBA_VDDRF", "WBA_VDDRFPA"}


def short(n):
    return n.split("/")[-1]


def net_of(desc):
    m = re.search(r"\[([^\]]*)\]", desc)
    return short(m.group(1)) if m else "?"


def ref_of(desc):
    m = re.search(r" of (\S+)", desc)
    return m.group(1) if m else None


def endpoint(desc, ref):
    m = re.search(r"Pad (\S+)", desc)
    if ref and m:
        return f"{ref}.{m.group(1)}"
    return desc[:30].replace("|", "/")


def main(cur, base, move_log, bom, pcb):
    d1, d0 = json.load(open(cur, encoding="utf8")), json.load(open(base, encoding="utf8"))
    ripped = set()
    for l in open(move_log, encoding="utf8"):
        if "ripped" in l:
            for m in re.finditer(r"\[([^\]]*)\]", l):
                ripped |= {x.strip().strip("'") for x in m.group(1).split(",") if x.strip()}
    parts = {r["Ref"]: r for r in csv.DictReader(open(bom, encoding="utf8"))}
    b = pcbnew.LoadBoard(pcb)
    netpads = defaultdict(list)
    for fp in b.GetFootprints():
        for p in fp.Pads():
            n = short(p.GetNetname())
            if n:
                netpads[n].append(f"{fp.GetReference()}.{p.GetNumber()}")

    def flag(ref):
        r = parts.get(ref, {})
        s = []
        if r.get("DNP"):
            s.append("DNP")
        if r.get("Status") in ("PLACEHOLDER",):
            s.append("PLACEHOLDER")
        return s

    groups = defaultdict(list)
    for u in d1["unconnected_items"]:
        a, c = u["items"]
        n = net_of(a["description"])
        gap = math.dist((a["pos"]["x"], a["pos"]["y"]), (c["pos"]["x"], c["pos"]["y"]))
        ra, rc = ref_of(a["description"]), ref_of(c["description"])
        fl = sorted({f"{r}:{f}" for r in (ra, rc) if r for f in flag(r)})
        g = "W" if n in WBA else "P" if fl else "R" if n in ripped else "G"
        ea = endpoint(a["description"], ra)
        ec = endpoint(c["description"], rc)
        groups[g].append((n, gap, ea, ec, fl, n in ripped))
    base_g = defaultdict(int)
    base_nets = defaultdict(int)
    for u in d0["unconnected_items"]:
        n = net_of(u["items"][0]["description"])
        base_nets[n] += 1

    title = {"W": "WBA55-related, waiting for the ST documents",
             "P": "Placeholder or intentionally unfitted endpoint (DNP / PLACEHOLDER part)",
             "R": "Opened by the approved placement rip-up",
             "G": "Genuine missing connections that existed before the placement change"}
    print("# Unconnected-pair reconciliation (generated by scripts/reconcile_unrouted.py)\n")
    print(f"Current DRC: {len(d1['unconnected_items'])} pairs. Baseline (tag baseline-routing-e8d141c): "
          f"{len(d0['unconnected_items'])} pairs.\n")
    print("| Group | Pairs | Nets |\n|---|---|---|")
    for g in "WPRG":
        print(f"| {g}: {title[g]} | {len(groups[g])} | {len({x[0] for x in groups[g]})} |")
    print()
    for g in "WPRG":
        print(f"## {g}. {title[g]} ({len(groups[g])} pairs)\n")
        print("| Net | Gap mm | End A | End B | Flags | Net ripped | Baseline pairs on net |")
        print("|---|---|---|---|---|---|---|")
        for n, gap, ea, ec, fl, rp in sorted(groups[g]):
            print(f"| {n} | {gap:.1f} | {ea} | {ec} | {' '.join(fl) or '-'} | {'yes' if rp else 'no'} | {base_nets.get(n, 0)} |")
        print()
    print("## Pads of every net that has an unconnected pair\n")
    print("| Net | Pads (part flags in brackets) |\n|---|---|")
    for n in sorted({x[0] for g in groups.values() for x in g}):
        pads = []
        for p in sorted(netpads[n]):
            f = flag(p.split(".")[0])
            pads.append(p + (f" [{'/'.join(f)}]" if f else ""))
        print(f"| {n} | {', '.join(pads)} |")
    print()
    gone = sorted(n for n in base_nets if n not in {x[0] for g in groups.values() for x in g})
    print(f"Baseline nets with unconnected pairs that have none now: {gone or 'none'}")


if __name__ == "__main__":
    main(*sys.argv[1:6])
